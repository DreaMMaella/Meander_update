-- Прочитанные уведомления в архиве.
--
-- Клиент помечает уведомление просмотренным архивацией (строка ленты уходит
-- в архив по VisibilityDetector), а `POST /notifications/:id/read` не зовёт
-- никто. Из-за этого read_at оставался NULL у всех, кто уже что-то просмотрел,
-- и плитка рисовала точку непрочитанного в архиве, который в UI подписан
-- «прочитанные уведомления».
--
-- Идемпотентно: повторный запуск ничего не меняет.

UPDATE notifications
   SET read_at = archived_at
 WHERE archived_at IS NOT NULL
   AND read_at IS NULL;
