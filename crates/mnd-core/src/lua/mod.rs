//! L3A: Lua как язык сценариев квеста (блок `call_lua`).
//!
//! Один [`LuaSession`] на сессию квеста (владеет [`crate::engine::GameEngine`]).
//! Скрипты поставляются как данные (inline-код блока), состояние движка
//! доступно Lua только через `core.get_var/set_var` и `core.get_table/set_table`,
//! а эффекты — через семейство `core.*` (`play_sound`, `set_item_visible`,
//! `open_link`, `go_to` …), которое повторяет записи блочного исполнителя.
//!
//! Паритет с блоками держится на одном канале: каждый `core.*`-эффект пишет
//! ровно те же служебные переменные (`_internal_audio_queue`,
//! `_internal_item_hidden`, …), что соответствующий блок, поэтому «Lua умеет то
//! же, что блоки» не требует второй пары путей в клиенте.
//!
//! Песочница: стандартные библиотеки доступны (`StdLib::ALL_SAFE` — все кроме
//! `debug` и C-модулей), но опасные для хоста функции обнуляются: `os.execute`/
//! `os.exit`/`os.remove`/`os.rename` и `io.popen`. `require` разрешён, но C-
//! модули недоступны (mlua `ALL_SAFE` гоняет `disable_c_modules`). Сеть наружу
//! только через посредника ядра (`core.*`).
//!
//! Потолки исполнения: один вызов блока не исполняет больше
//! `MAX_LUA_INSTRUCTIONS` инструкций (иначе `while true do end` из чужого
//! квеста навечно вешает поток движка), а перенос значения Lua ↔ JSON
//! обрезается на `MAX_LUA_VALUE_DEPTH` — циклическая таблица без потолка
//! кончается не ошибкой, а переполнением стека.
//!
//! Изменения состояния применяются диффом после возврата функции (не посреди
//! вызова): `core.*` работает со снимком, а не с живым runtime, поэтому
//! dirty-наборы движка не засоряются и Lua не наблюдает промежуточные
//! мутации других блоков.
pub mod completion;

// Две реализации одной сигнатуры. Разделение нужно не для удобства, а потому
// что `mlua` — C (vendored lua-src), и в wasm32-unknown-unknown его build-скрипт
// падает: «don't know how to build Lua for wasm32-unknown-unknown».
//
// Заглушка повторяет сигнатуры один в один, поэтому `mnd-ffi` и сгенерированный
// `frb_generated` остаются одни для всех платформ — расхождения веб-ветки от
// нативной нет. Меняется только поведение: квест на Lua (3 из 227) получает
// явную ошибку блока вместо молча другого результата.
#[cfg(feature = "lua-scripting")]
mod mlua_session;
#[cfg(feature = "lua-scripting")]
pub use mlua_session::{LuaSession, json_to_lua, lua_to_json};

#[cfg(not(feature = "lua-scripting"))]
mod session_stub;
#[cfg(not(feature = "lua-scripting"))]
pub use session_stub::LuaSession;
